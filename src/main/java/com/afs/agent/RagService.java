package com.afs.agent;

import com.fasterxml.jackson.databind.ObjectMapper;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.concurrent.atomic.AtomicReference;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.context.annotation.Profile;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * Retrieval-augmented generation over the workspace corpus.
 *
 * <p>Articles, reader feedback and ad copy are chunked, embedded locally and stored in H2. Search
 * is hybrid: cosine similarity over the embeddings plus a keyword overlap score, which keeps
 * exact-term queries (model numbers, legal phrases) from being drowned by fuzzy neighbours.
 * Answers are generated by the configured LLM with numbered citations, and degrade to an
 * extractive answer when no model is configured, so the feature never blocks on credentials.
 */
@Profile("local-cms")
class RagService {
    private static final Logger log = LoggerFactory.getLogger(RagService.class);
    private static final int CHUNK_SIZE = 520;
    private static final int CHUNK_OVERLAP = 80;
    private static final int MAX_CHUNKS_PER_DOC = 12;

    record Hit(long chunkId, String docType, String docId, String site, String title,
               int chunkIndex, String content, double vectorScore, double keywordScore, double score) {}

    record Citation(String docType, String docId, String site, String title, int chunkIndex, String snippet) {}

    record Answer(String answer, List<Citation> citations, int promptTokens, int completionTokens,
                  long latencyMs, boolean cacheHit, String model, int promptVersion) {}

    private final JdbcTemplate db;
    private final ObjectMapper json;
    private final PromptRegistry prompts;
    private final AiModelGateway gateway;
    private final SemanticCache cache;
    private final AtomicReference<Map<String, Object>> indexStats = new AtomicReference<>(Map.of());

    RagService(JdbcTemplate db, ObjectMapper json, PromptRegistry prompts, AiModelGateway gateway,
               SemanticCache cache) {
        this.db = db;
        this.json = json;
        this.prompts = prompts;
        this.gateway = gateway;
        this.cache = cache;
    }

    /** Rebuilds the chunk index for every publisher; safe to run repeatedly. */
    Map<String, Object> rebuildIndex() {
        long started = System.currentTimeMillis();
        db.update("DELETE FROM ai_rag_chunk");
        int docs = 0;
        int chunks = 0;
        for (var article : db.queryForList("""
                SELECT article_id, site, title, first_part, text_list FROM article_info
                WHERE partner = 'AFS Media' AND title IS NOT NULL
                """)) {
            String body = article.get("first_part") + "\n" + readable(article.get("text_list"));
            chunks += indexDocument("article", str(article.get("article_id")), str(article.get("site")),
                    str(article.get("title")), body);
            docs++;
        }
        for (var feedback : db.queryForList("""
                SELECT site, CAST(`value` AS VARCHAR) AS body, ctime FROM feedback
                WHERE CAST(`value` AS VARCHAR) IS NOT NULL
                """)) {
            chunks += indexDocument("feedback", str(feedback.get("site")) + "-" + str(feedback.get("ctime")),
                    str(feedback.get("site")), "读者反馈 · " + str(feedback.get("site")),
                    str(feedback.get("body")));
            docs++;
        }
        for (var copy : db.queryForList("SELECT name, CAST(ad_text AS VARCHAR) AS body FROM ad_text")) {
            chunks += indexDocument("copy", str(copy.get("name")), "", "广告文案 · " + str(copy.get("name")),
                    readable(copy.get("body")));
            docs++;
        }
        Map<String, Object> stats = new LinkedHashMap<>();
        stats.put("documents", docs);
        stats.put("chunks", chunks);
        stats.put("dimensions", LocalEmbedding.DIM);
        stats.put("embedding", "local-hash-384");
        stats.put("rebuildMs", System.currentTimeMillis() - started);
        stats.put("builtAt", java.time.OffsetDateTime.now().toString());
        indexStats.set(stats);
        log.info("RAG index rebuilt: {} documents, {} chunks in {} ms", docs, chunks, stats.get("rebuildMs"));
        return stats;
    }

    private int indexDocument(String docType, String docId, String site, String title, String body) {
        List<String> pieces = chunk(title, body);
        int written = 0;
        for (int i = 0; i < pieces.size(); i++) {
            String content = pieces.get(i);
            String embedding = LocalEmbedding.encode(LocalEmbedding.embed(content));
            db.update("""
                    INSERT INTO ai_rag_chunk (doc_type, doc_id, site, title, chunk_index, content, tokens, embedding)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                    """, docType, docId, site, title, i, content, LocalEmbedding.tokens(content), embedding);
            written++;
        }
        return written;
    }

    /** Splits on paragraph boundaries first so a chunk never starts mid-sentence. */
    private List<String> chunk(String title, String body) {
        String heading = title == null ? "" : title.strip();
        String normalized = (body == null ? "" : body).replace("\\r", "").strip();
        List<String> chunks = new ArrayList<>();
        StringBuilder current = new StringBuilder(heading.isEmpty() ? "" : heading + "\n");
        for (String paragraph : normalized.split("\\n+")) {
            String piece = paragraph.strip();
            if (piece.isEmpty()) continue;
            while (piece.length() > CHUNK_SIZE) {
                int cut = piece.lastIndexOf('.', CHUNK_SIZE);
                if (cut < CHUNK_SIZE / 2) cut = CHUNK_SIZE;
                current.append(piece, 0, cut).append(' ');
                chunks.add(current.toString().strip());
                current = new StringBuilder();
                piece = piece.substring(Math.max(0, cut - CHUNK_OVERLAP)).strip();
                if (chunks.size() >= MAX_CHUNKS_PER_DOC) return chunks;
            }
            if (current.length() + piece.length() > CHUNK_SIZE && current.length() > 0) {
                chunks.add(current.toString().strip());
                current = new StringBuilder();
                if (chunks.size() >= MAX_CHUNKS_PER_DOC) return chunks;
            }
            current.append(piece).append('\n');
        }
        if (current.length() > 40) chunks.add(current.toString().strip());
        if (chunks.isEmpty() && !heading.isEmpty()) chunks.add(heading);
        return chunks.size() > MAX_CHUNKS_PER_DOC ? chunks.subList(0, MAX_CHUNKS_PER_DOC) : chunks;
    }

    /**
     * Bilingual query expansion.
     *
     * <p>The local embedding is monolingual: a Chinese question shares almost no tokens with an
     * English corpus, so recall would collapse. Operators still ask in Chinese, so the query is
     * rewritten with the domain glossary before embedding — the same trick used to bridge a
     * local embedding and a second-language corpus without paying for a translation call.
     */
    private static final java.util.Map<String, String> GLOSSARY = java.util.Map.ofEntries(
            java.util.Map.entry("跑步机", "treadmill walking pad"),
            java.util.Map.entry("折叠", "foldable compact"),
            java.util.Map.entry("公寓", "apartment small space"),
            java.util.Map.entry("噪音", "noise decibel quiet"),
            java.util.Map.entry("种植牙", "dental implant"),
            java.util.Map.entry("牙", "dental tooth"),
            java.util.Map.entry("太阳能", "solar panel"),
            java.util.Map.entry("储能", "battery backup storage"),
            java.util.Map.entry("冰箱", "fridge refrigerator runtime"),
            java.util.Map.entry("信用卡", "credit card travel"),
            java.util.Map.entry("货币转换费", "foreign transaction fee"),
            java.util.Map.entry("餐盒", "meal kit delivery"),
            java.util.Map.entry("配送", "delivery shipping"),
            java.util.Map.entry("保险", "insurance policy"),
            java.util.Map.entry("自付额", "deductible"),
            java.util.Map.entry("广告", "advertising campaign"),
            java.util.Map.entry("素材", "creative asset"),
            java.util.Map.entry("预算", "budget spend"),
            java.util.Map.entry("投放", "campaign delivery"),
            java.util.Map.entry("合规", "compliance policy"),
            java.util.Map.entry("价格", "price cost"),
            java.util.Map.entry("退款", "refund return"),
            java.util.Map.entry("反馈", "feedback review"),
            java.util.Map.entry("标题", "headline title"),
            java.util.Map.entry("德国", "germany german"),
            java.util.Map.entry("美国", "united states us")
    );

    static String expandQuery(String query) {
        if (query == null || query.isBlank()) return query;
        StringBuilder expanded = new StringBuilder(query);
        for (var entry : GLOSSARY.entrySet()) {
            if (query.contains(entry.getKey())) expanded.append(' ').append(entry.getValue());
        }
        return expanded.toString();
    }

    List<Hit> search(String query, String site, int topK) {
        String expandedQuery = expandQuery(query);
        float[] queryVector = LocalEmbedding.embed(expandedQuery);
        List<String> queryTerms = terms(expandedQuery);
        List<Hit> hits = new ArrayList<>();
        String sql = "SELECT id, doc_type, doc_id, site, title, chunk_index, content, embedding FROM ai_rag_chunk"
                + (site == null || site.isBlank() ? "" : " WHERE site = ?");
        Object[] args = site == null || site.isBlank() ? new Object[]{} : new Object[]{site};
        db.query(sql, (rs, rowNum) -> {
            String content = rs.getString("content");
            double vectorScore = LocalEmbedding.cosine(queryVector, LocalEmbedding.decode(rs.getString("embedding")));
            double keywordScore = keywordScore(queryTerms, content);
            double score = 0.72 * vectorScore + 0.28 * keywordScore;
            hits.add(new Hit(rs.getLong("id"), rs.getString("doc_type"), rs.getString("doc_id"),
                    rs.getString("site"), rs.getString("title"), rs.getInt("chunk_index"), content,
                    round4(vectorScore), round4(keywordScore), round4(score)));
            return null;
        }, args);
        hits.sort((left, right) -> Double.compare(right.score(), left.score()));
        return hits.subList(0, Math.min(Math.max(1, topK), hits.size()));
    }

    Answer answer(String question, String site, int topK) {
        return answer(question, site, topK, true);
    }

    /** {@code allowCache=false} is used by the eval harness so latency numbers stay honest. */
    Answer answer(String question, String site, int topK, boolean allowCache) {
        long started = System.currentTimeMillis();
        List<Hit> hits = search(question, site, topK);
        StringBuilder context = new StringBuilder();
        List<Citation> citations = new ArrayList<>();
        for (int i = 0; i < hits.size(); i++) {
            Hit hit = hits.get(i);
            context.append('[').append(i + 1).append("] ").append(hit.title()).append(" — ")
                    .append(abbreviate(hit.content(), 700)).append('\n');
            citations.add(new Citation(hit.docType(), hit.docId(), hit.site(), hit.title(),
                    hit.chunkIndex(), abbreviate(hit.content(), 220)));
        }
        String prompt = prompts.render("rag.answer", Map.of("question", question, "context", context.toString()));
        int version = prompts.activeVersion("rag.answer");

        if (!gateway.isConfigured()) {
            String extractive = extractiveAnswer(question, hits);
            return new Answer(extractive, citations, LocalEmbedding.tokens(prompt), 0,
                    System.currentTimeMillis() - started, false, "extractive-fallback", version);
        }
        var cached = allowCache ? cache.lookup(prompt) : null;
        if (cached != null) {
            return new Answer(cached.answer(), citations, LocalEmbedding.tokens(prompt), 0,
                    System.currentTimeMillis() - started, true, cached.model(), version);
        }
        try {
            var resolved = gateway.resolve();
            if (resolved == null) throw new IllegalStateException("AI 平台未配置");
            var call = gateway.chat(resolved, List.of(dev.langchain4j.data.message.UserMessage.from(prompt)), List.of());
            String text = call.message() == null || call.message().text() == null ? "" : call.message().text().strip();
            if (text.isEmpty()) throw new IllegalStateException("模型返回空内容");
            if (allowCache) cache.store(resolved.chatModel(), prompt, text, call.inputTokens() + call.outputTokens());
            return new Answer(text, citations, call.inputTokens(), call.outputTokens(),
                    System.currentTimeMillis() - started, false, call.modelName(), version);
        } catch (Exception failure) {
            log.warn("RAG answer degraded to extractive mode: {}", failure.getMessage());
            return new Answer(extractiveAnswer(question, hits), citations, LocalEmbedding.tokens(prompt), 0,
                    System.currentTimeMillis() - started, false, "extractive-fallback", version);
        }
    }

    private String extractiveAnswer(String question, List<Hit> hits) {
        if (hits.isEmpty()) return "知识库中没有与该问题相关的片段，请先重建索引或补充内容。";
        StringBuilder answer = new StringBuilder("（未配置大模型，按检索片段摘录最相关内容）\n");
        int limit = Math.min(3, hits.size());
        for (int i = 0; i < limit; i++) {
            answer.append('[').append(i + 1).append("] ").append(abbreviate(hits.get(i).content(), 320)).append('\n');
        }
        answer.append("\n问题：").append(question);
        return answer.toString();
    }

    int activePromptVersion() {
        return prompts.activeVersion("rag.answer");
    }

    Map<String, Object> stats() {
        Integer chunks = db.queryForObject("SELECT COUNT(*) FROM ai_rag_chunk", Integer.class);
        Integer docs = db.queryForObject("SELECT COUNT(DISTINCT doc_type || ':' || doc_id) FROM ai_rag_chunk",
                Integer.class);
        Map<String, Object> stats = new LinkedHashMap<>();
        stats.put("chunks", chunks == null ? 0 : chunks);
        stats.put("documents", docs == null ? 0 : docs);
        stats.put("dimensions", LocalEmbedding.DIM);
        stats.put("embedding", "local-hash-384");
        stats.put("lastRebuild", indexStats.get());
        return stats;
    }

    boolean isEmpty() {
        Integer chunks = db.queryForObject("SELECT COUNT(*) FROM ai_rag_chunk", Integer.class);
        return chunks == null || chunks == 0;
    }

    private static List<String> terms(String text) {
        List<String> out = new ArrayList<>();
        if (text == null) return out;
        for (String token : text.toLowerCase(Locale.ROOT).replaceAll("[^\\p{L}\\p{N}]+", " ").trim().split("\\s+")) {
            if (token.length() >= 2) out.add(token);
        }
        return out;
    }

    private static double keywordScore(List<String> queryTerms, String content) {
        if (queryTerms.isEmpty() || content == null) return 0;
        String lower = content.toLowerCase(Locale.ROOT);
        int matched = 0;
        for (String term : queryTerms) if (lower.contains(term)) matched++;
        return (double) matched / queryTerms.size();
    }

    private String readable(Object raw) {
        if (raw == null) return "";
        String text = str(raw);
        if (!text.trim().startsWith("[")) return text;
        try {
            List<String> parts = json.readValue(text, new com.fasterxml.jackson.core.type.TypeReference<>() {});
            return String.join("\n", parts);
        } catch (Exception ignored) {
            return text;
        }
    }

    private static String str(Object value) {
        return value == null ? "" : String.valueOf(value);
    }

    private static String abbreviate(String value, int limit) {
        if (value == null) return "";
        String text = value.replaceAll("\\s+", " ").strip();
        return text.length() <= limit ? text : text.substring(0, limit) + "…";
    }

    private static double round4(double value) {
        return Math.round(value * 10_000d) / 10_000d;
    }
}
